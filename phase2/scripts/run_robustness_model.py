from pathlib import Path
import argparse, json, sys
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'src'))
from chile_phase2.robustness import deterministic_subset, english_prompt
from chile_phase2.robustness_execution import run_robustness
from chile_phase2.openrouter import verify_frozen_models


def main():
    ap=argparse.ArgumentParser(); ap.add_argument('--label',required=True); ap.add_argument('--cap-usd',type=float,required=True); args=ap.parse_args()
    study=json.loads((ROOT/'config/study.json').read_text(encoding='utf-8'))
    cfg=json.loads((ROOT/'config/models.json').read_text(encoding='utf-8'))
    model=next(m for m in cfg['models'] if m['label']==args.label)
    verify_frozen_models({'models':[model]},verify_providers=True)
    subset=deterministic_subset(ROOT)
    plan=[]
    for rep in (1,2):
        for p in subset: plan.append(('stability',rep,p))
    for p in subset: plan.append(('english',1,english_prompt(ROOT,p)))
    outdir=ROOT/'results/robustness/raw'; outdir.mkdir(parents=True,exist_ok=True); out=outdir/f'{args.label}.jsonl'
    done=set(); cost=0.0
    if out.exists():
        for line in out.read_text(encoding='utf-8').splitlines():
            if line.strip():
                r=json.loads(line); done.add(r['request_identity']); cost+=float(r.get('cost_usd') or 0)
    with out.open('a',encoding='utf-8') as f:
        for i,(family,rep,prompt) in enumerate(plan,1):
            # Identity is generated by the exact runner. Reruns are deduplicated from existing rows by family/rep/prompt.
            logical=f'{family}|{rep}|{prompt["prompt_id"]}'
            if any(json.loads(line).get('logical_cell')==logical for line in out.read_text(encoding='utf-8').splitlines() if line.strip()): continue
            if cost+0.01>args.cap_usd: raise RuntimeError(f'Robustness cap would be exceeded for {args.label}: {cost:.4f}/{args.cap_usd:.4f}')
            r=run_robustness(model,prompt,study,family,rep,cost,max_retries=4); r['logical_cell']=logical
            cost+=float(r.get('cost_usd') or 0)
            if cost>args.cap_usd: raise RuntimeError(f'Robustness cap exceeded for {args.label}')
            f.write(json.dumps(r,ensure_ascii=False,sort_keys=True)+'\n'); f.flush()
            if i%25==0 or i==len(plan): print(args.label,i,'/',len(plan),f'cost=${cost:.4f}')
    rows=[json.loads(x) for x in out.read_text(encoding='utf-8').splitlines() if x.strip()]
    if len(rows)!=156: raise RuntimeError(f'{args.label} robustness row count {len(rows)} != 156')
    print('ROBUSTNESS MODEL COMPLETE',args.label,'rows=',len(rows),f'cost=${cost:.4f}')

if __name__=='__main__': main()
